def translator(language: str):
    def translate(message_id: str, **values: object) -> str:
        return MESSAGES[language][message_id].format(**values)
    return translate


def argument_message(message: str, language: str) -> str:
    """Translate argparse's fixed error vocabulary without changing globals."""
    if language == "en":
        return message
    replacements = {
        "unrecognized arguments:": "无法识别的参数：",
        "expected one argument": "需要一个参数值",
        "invalid choice:": "无效选项：",
        "choose from": "可选值",
        "not allowed with argument": "不能同时使用参数",
        "the following arguments are required:": "缺少以下必需参数：",
        "argument ": "参数 ",
    }
    for source, target in replacements.items():
        message = message.replace(source, target)
    return message
